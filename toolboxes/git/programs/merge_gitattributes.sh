# Merge the toolbox .gitattributes template and every toolbox's
# project.gitattributes into the project .gitattributes.
#
# The generated lines sit in one marked block at the top of the file, in order
# (template first, then toolboxes by path, then the project's own
# .toolboxes/git_toolbox/project.gitattributes), without duplicates. Attribute order
# matters in git (later lines win), so nothing is sorted. Lines outside the
# block are the project's own: they are kept, after the block, so they override
# it. A line outside the block that the block now provides is dropped, which
# also migrates the old hand-seeded `* text=auto eol=lf`.
# The project's file is deduplicated only against itself, so a line it repeats
# from an earlier fragment still lands last and wins.
# Usage: merge_gitattributes <project-root> <template>
root=$1
template=$2
dest=$root/.gitattributes
project_file=$root/.toolboxes/git_toolbox/project.gitattributes
begin='# >>> toolbox-managed: generated by the git toolbox, edit the toolbox settings >>>'
end='# <<< toolbox-managed <<<'

managed=$(mktemp "$root/.gitattributes.XXXXXX")
tmp=$(mktemp "$root/.gitattributes.XXXXXX")
trap 'rm -f "$managed" "$tmp"' EXIT

{
  {
    cat "$template"
    echo
    # Only the toolboxes' own project.gitattributes files
    # (.toolboxes/<name>/project.gitattributes), not those of nested projects.
    # The git toolbox's own file is the project's and is added last, below.
    if [ -d "$root/.toolboxes" ]; then
      while IFS= read -r -d '' f; do
        cat "$f"
        echo
      done < <(find "$root/.toolboxes" -mindepth 2 -maxdepth 2 -name project.gitattributes -type f ! -path "$project_file" -print0 | sort -z)
    fi
  } | awk 'NF && !seen[$0]++'
  # The project's own file, last so its lines win.
  if [ -f "$project_file" ]; then
    awk 'NF && !seen[$0]++' "$project_file"
  fi
} >"$managed"

user=
if [ -f "$dest" ]; then
  user=$(awk -v b="$begin" -v e="$end" '
    NR == FNR { m[$0] = 1; next }
    $0 == b { skip = 1; next }
    $0 == e { skip = 0; next }
    skip || ($0 in m) { next }
    NF { started = 1 }
    started { print }
  ' "$managed" "$dest")
fi

{
  echo "$begin"
  cat "$managed"
  echo "$end"
  if [ -n "$user" ]; then
    echo
    printf '%s\n' "$user"
  fi
} >"$tmp"

chmod 0644 "$tmp"
if [ ! -f "$dest" ] || ! cmp -s "$tmp" "$dest"; then
  mv "$tmp" "$dest"
fi
