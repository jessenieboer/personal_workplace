# Merge the toolbox .gitattributes template and every toolbox's
# project.gitattributes into the project .gitattributes.
#
# The generated lines sit in one marked block at the top of the file, in order
# (template first, then toolboxes by path), without duplicates. Attribute order
# matters in git (later lines win), so nothing is sorted. Lines outside the
# block are the project's own: they are kept, after the block, so they override
# it. A line outside the block that the block now provides is dropped, which
# also migrates the old hand-seeded `* text=auto eol=lf`.
# Usage: merge_gitattributes <project-root> <template>
root=$1
template=$2
dest=$root/.gitattributes
begin='# >>> toolbox-managed: generated by the git toolbox, edit the toolbox settings >>>'
end='# <<< toolbox-managed <<<'

managed=$(mktemp "$root/.gitattributes.XXXXXX")
tmp=$(mktemp "$root/.gitattributes.XXXXXX")
trap 'rm -f "$managed" "$tmp"' EXIT

{
  cat "$template"
  echo
  # Only the toolboxes' own project.gitattributes files
  # (.toolboxes/<name>/project.gitattributes), not those of nested projects.
  if [ -d "$root/.toolboxes" ]; then
    while IFS= read -r -d '' f; do
      cat "$f"
      echo
    done < <(find "$root/.toolboxes" -mindepth 2 -maxdepth 2 -name project.gitattributes -type f -print0 | sort -z)
  fi
} | awk 'NF && !seen[$0]++' >"$managed"

user=
if [ -f "$dest" ]; then
  user=$(awk -v b="$begin" -v e="$end" '
    NR == FNR { m[$0] = 1; next }
    $0 == b { skip = 1; next }
    $0 == e { skip = 0; next }
    skip || ($0 in m) { next }
    NF { started = 1 }
    started { print }
  ' "$managed" "$dest")
fi

{
  echo "$begin"
  cat "$managed"
  echo "$end"
  if [ -n "$user" ]; then
    echo
    printf '%s\n' "$user"
  fi
} >"$tmp"

chmod 0644 "$tmp"
if [ ! -f "$dest" ] || ! cmp -s "$tmp" "$dest"; then
  mv "$tmp" "$dest"
fi
