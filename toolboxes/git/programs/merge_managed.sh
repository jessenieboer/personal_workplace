# Merge every toolbox's settings/<name> (.toolboxes/*/settings/.gitignore or
# .gitattributes) into the project's root <name>.
#
# The generated lines sit in one marked block at the top of the file, in order
# (the git toolbox's own file first, then the other toolboxes by path, then the
# optional project file), without duplicates. Order matters in both formats
# (later lines win), so nothing is sorted. Lines outside the block are the
# project's own: they are kept, after the block, so they override it. A line
# outside the block that the block now provides is dropped, which also migrates
# a file this script used to write whole.
# The project file is deduplicated only against itself, so a line it repeats
# from an earlier file still lands last and wins.
# Usage: merge_managed <project-root> <name> [<project-file-relative-path>]
root=$1
name=$2
project_file=${3:+$root/$3}
dest=$root/$name
base=$root/.toolboxes/git_toolbox/settings/$name
begin='# >>> toolbox-managed: generated by the git toolbox, edit the toolbox settings >>>'
end='# <<< toolbox-managed <<<'

managed=$(mktemp "$dest.XXXXXX")
tmp=$(mktemp "$dest.XXXXXX")
trap 'rm -f "$managed" "$tmp"' EXIT

{
  {
    if [ -f "$base" ]; then
      cat "$base"
      echo
    fi
    # Only the toolboxes' own files (.toolboxes/<toolbox>/settings/<name>),
    # not those of nested projects.
    if [ -d "$root/.toolboxes" ]; then
      while IFS= read -r -d '' f; do
        cat "$f"
        echo
      done < <(find "$root/.toolboxes" -mindepth 3 -maxdepth 3 -name "$name" -type f \
        -path '*/settings/*' ! -path "$base" -print0 | sort -z)
    fi
  } | awk 'NF && !seen[$0]++'
  # The project's own file, last so its lines win.
  if [ -n "$project_file" ] && [ -f "$project_file" ]; then
    awk 'NF && !seen[$0]++' "$project_file"
  fi
} >"$managed"

user=
if [ -f "$dest" ]; then
  user=$(awk -v b="$begin" -v e="$end" '
    NR == FNR { m[$0] = 1; next }
    $0 == b { skip = 1; next }
    $0 == e { skip = 0; next }
    skip || ($0 in m) { next }
    NF { started = 1 }
    started { print }
  ' "$managed" "$dest")
fi

{
  echo "$begin"
  cat "$managed"
  echo "$end"
  if [ -n "$user" ]; then
    echo
    printf '%s\n' "$user"
  fi
} >"$tmp"

chmod 0644 "$tmp"
if [ ! -f "$dest" ] || ! cmp -s "$tmp" "$dest"; then
  mv "$tmp" "$dest"
fi
# A file written 0600 by an older run (mktemp default).
chmod 0644 "$dest"
