# Remove <file> only if it is byte-identical to one of the candidates, i.e.
# something the toolbox itself generated. Any other file is left alone.
# Usage: remove_generated <file> <candidate>...
file=$1
shift

[ -e "$file" ] || exit 0
for candidate in "$@"; do
  if cmp -s "$candidate" "$file"; then
    rm -f -- "$file"
    exit 0
  fi
done
echo "left $file in place: it was not generated by the toolbox" >&2
