# Merge every toolbox's *dir_locals fragment into one .dir-locals.el.
# Usage: merge_dir_locals <project-root> <dest>
root=$1
dest=$2

tmp=$(mktemp "$(dirname "$dest")/.dir-locals.el.XXXXXX")
trap 'rm -f "$tmp"' EXIT

# Fragments in path order. A repeated variable takes the value from the
# later fragment, so emacs_toolbox's org-directory yields to
# project_management_toolbox's.
fragments=()
if [ -d "$root/.toolboxes" ]; then
  while IFS= read -r -d '' f; do
    fragments+=("$f")
  done < <(find "$root/.toolboxes" -type f -name '*dir_locals' -print0 | LC_ALL=C sort -z)
fi

{
  cat <<'HEADER'
;; Generated by emacs toolbox enterShell
;; Do not edit this file directly — it will be overwritten on shell entry.
HEADER
  # Emacs reads only the first form of .dir-locals.el, so splice every
  # fragment's ((MODE . VARS) ...) into one list. Repeated MODE keys are
  # fine: dir-locals applies every matching entry. org-capture-templates
  # would be replaced, not added to, so the merger concatenates those.
  if [ "${#fragments[@]}" -gt 0 ]; then
    merge_capture_templates "${fragments[@]}"
  fi
} >"$tmp"

if [ ! -f "$dest" ] || ! cmp -s "$tmp" "$dest"; then
  mv "$tmp" "$dest"
fi
